// Regenerates src/lib/typings-data.ts from the N/ declarations in @hitc/netsuite-types.
// Run with --check to fail (for CI) when the committed data is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { formatWithBiome } from "./biome.ts";
import { extractTypings } from "./typings-extract.ts";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const target = join(root, "src/lib/typings-data.ts");

const source = `// What the type definitions say about each module: the options its functions take,
// its enums and its exports. Generated by scripts/sync-typings.ts from
// @hitc/netsuite-types (MIT licence, https://github.com/headintheclouddev/typings-suitescript-2.0).
import type { Typings } from "./typings.ts";

export const TYPINGS: Typings = ${JSON.stringify(extractTypings())};
`;

if (process.argv.includes("--check")) {
  const current = readFileSync(target, "utf8");
  writeFileSync(target, source);
  formatWithBiome(target);
  const next = readFileSync(target, "utf8");
  writeFileSync(target, current);
  if (next !== current) {
    console.error(
      "src/lib/typings-data.ts is out of date; run npm run sync-typings",
    );
    process.exit(1);
  }
} else {
  writeFileSync(target, source);
  formatWithBiome(target);
  console.log("Wrote src/lib/typings-data.ts");
}
