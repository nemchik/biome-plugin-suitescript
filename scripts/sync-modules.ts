// Regenerates src/lib/modules.ts from the N/ module declarations in @hitc/netsuite-types.
// Existing identifiers are kept; new modules default to their last path segment.
// Run with --check to fail (for CI) when the committed list is out of date.
import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { MODULES } from "../src/lib/modules.ts";
import { formatWithBiome } from "./biome.ts";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const typesDir = join(root, "node_modules/@hitc/netsuite-types/N");

// Plugin implementation types are not loadable modules (N/types is one).
const SKIP = [/^plugins\//];

function walk(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) return walk(path);
    return entry.name.endsWith(".d.ts") ? [path] : [];
  });
}

const found = walk(typesDir)
  .map((file) =>
    relative(typesDir, file)
      .replaceAll("\\", "/")
      .replace(/\.d\.ts$/, ""),
  )
  .filter((name) => !SKIP.some((re) => re.test(name)))
  .map((name) => `N/${name}`);

const next: Record<string, string> = { ...MODULES };
for (const name of found) next[name] ??= name.split("/").at(-1) as string;

const sorted = Object.fromEntries(
  Object.entries(next).sort(([a], [b]) => a.localeCompare(b)),
);
const source = `// Valid SuiteScript 2.x modules and their conventional identifiers.
// Generated by scripts/sync-modules.ts from @hitc/netsuite-types.
export const MODULES: Record<string, string> = ${JSON.stringify(sorted, null, 2)};
`;

const added = found.filter((name) => !(name in MODULES));
if (process.argv.includes("--check")) {
  if (added.length) {
    console.error(
      `src/lib/modules.ts is missing: ${added.join(", ")}. Run npm run sync-modules.`,
    );
    process.exit(1);
  }
} else {
  const target = join(root, "src/lib/modules.ts");
  writeFileSync(target, source);
  formatWithBiome(target);
  console.log(
    added.length ? `Added: ${added.join(", ")}` : "Module list is up to date.",
  );
}
