#!/usr/bin/env node
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { relative, resolve } from "node:path";
import { glob } from "tinyglobby";
import { analyzeSource } from "../cli/analyze.ts";
import { type FileResult, format, type OutputFormat } from "../cli/format.ts";
import { MODULES } from "../lib/modules.ts";

const USAGE = `Usage:
  biome-plugin-suitescript check [globs...] [--config file] [--format text|json|github]
  biome-plugin-suitescript generate module-vars [--set N/module=identifier]... [--out file.js]

check reads "includes" from biome-plugin-suitescript.json unless globs are given.
Exit codes: 0 clean, 1 problems found, 2 usage or configuration error.`;

function fail(message: string): never {
  console.error(`${message}\n\n${USAGE}`);
  process.exit(2);
}

function parseFlags(
  args: string[],
  valued: string[],
): { flags: Record<string, string[]>; positional: string[] } {
  const flags: Record<string, string[]> = {};
  const positional: string[] = [];
  for (let i = 0; i < args.length; i++) {
    const arg = args[i] as string;
    if (!arg.startsWith("--")) {
      positional.push(arg);
      continue;
    }
    const name = arg.slice(2);
    if (!valued.includes(name)) fail(`Unknown option --${name}`);
    const value = args[i + 1];
    if (value === undefined) fail(`--${name} needs a value`);
    flags[name] = [...(flags[name] ?? []), value];
    i++;
  }
  return { flags, positional };
}

const isOutputFormat = (value: string): value is OutputFormat =>
  value === "text" || value === "json" || value === "github";

function readIncludes(configPath: string): string[] {
  if (!existsSync(configPath)) {
    fail(
      `No globs given and no ${relative(process.cwd(), configPath)} found. List your script sources in "includes".`,
    );
  }
  let config: { includes?: unknown };
  try {
    config = JSON.parse(readFileSync(configPath, "utf8"));
  } catch (error) {
    fail(
      `Could not read ${configPath}: ${error instanceof Error ? error.message : error}`,
    );
  }
  const includes = config.includes;
  if (
    !Array.isArray(includes) ||
    includes.length === 0 ||
    includes.some((g) => typeof g !== "string")
  ) {
    fail(`${configPath}: "includes" must be a non-empty array of glob strings`);
  }
  return includes as string[];
}

async function check(args: string[]): Promise<never> {
  const { flags, positional } = parseFlags(args, ["config", "format"]);
  const kind = flags.format?.[0] ?? "text";
  if (!isOutputFormat(kind)) fail(`Unknown format '${kind}'`);

  const includes =
    positional.length > 0
      ? positional
      : readIncludes(
          resolve(flags.config?.[0] ?? "biome-plugin-suitescript.json"),
        );

  const files = (
    await glob(includes, { ignore: ["**/node_modules/**"], onlyFiles: true })
  ).sort();
  if (files.length === 0) fail(`No files matched: ${includes.join(", ")}`);

  const results: FileResult[] = [];
  let upgrade = false;
  for (const file of files) {
    const analysis = analyzeSource(file, readFileSync(file, "utf8"));
    upgrade ||= analysis.upgrade;
    results.push({ diagnostics: analysis.diagnostics, file });
  }
  const output = format(kind, results, { files: files.length, upgrade });
  if (output) console.log(output);
  process.exit(results.some((r) => r.diagnostics.length) ? 1 : 0);
}

// Biome cannot resolve bare package imports from plugins, so the generated rule
// inlines the compiled parsers from this package.
function inline(file: string): string {
  return readFileSync(new URL(`../lib/${file}`, import.meta.url), "utf8")
    .replace(/^import .*\n/gm, "")
    .replace(/^export \{ stringValue \};\n?/m, "")
    .replaceAll("export ", "");
}

function generate(args: string[]): void {
  const [kind, ...rest] = args;
  if (kind !== "module-vars") fail("generate supports: module-vars");
  const { flags } = parseFlags(rest, ["set", "out"]);
  const map: Record<string, string> = { ...MODULES };
  for (const entry of flags.set ?? []) {
    const [name, id] = entry.split("=");
    if (!name || !id) fail("--set expects N/module=identifier");
    map[name] = id;
  }
  const out = flags.out?.[0] ?? "suitescript-module-vars.js";

  writeFileSync(
    out,
    `// Generated by biome-plugin-suitescript. Add to biome.json "plugins".
import { defineRule, ast, registerDiagnostic } from "@biomejs/runtime/plugin";

${inline("define.js")}
${inline("biome-modules.js")}
const MODULES = ${JSON.stringify(map, null, 2)};

export const moduleVars = defineRule({
\tquery: ast("JS_CALL_EXPRESSION", "JS_IMPORT"),
\trun(node) {
\t\tfor (const { name, param } of dependencies(node)) {
\t\t\tconst expected = name && Object.hasOwn(MODULES, name) ? MODULES[name] : undefined;
\t\t\tif (expected && param && param.text !== expected) {
\t\t\t\tregisterDiagnostic(param, "warning", \`Identifier for \${name} should be '\${expected}'.\`);
\t\t\t}
\t\t}
\t},
});
`,
  );
  console.log(`Wrote ${out}`);
}

const [command, ...args] = process.argv.slice(2);
if (command === "check") await check(args);
else if (command === "generate") generate(args);
else fail(command ? `Unknown command '${command}'` : "Missing command");
